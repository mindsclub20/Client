import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const htmlPath = join(root, "public", "site-source.html");
const outPath = join(root, "lib", "generated-site-source.ts");

const html = readFileSync(htmlPath, "utf8");
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(
  outPath,
  `/* Auto-generated by scripts/embed-site-source.mjs — do not edit */\nexport const SITE_SOURCE_HTML = ${JSON.stringify(html)};\n`,
  "utf8"
);
console.log(`Embedded ${html.length} bytes into lib/generated-site-source.ts`);
